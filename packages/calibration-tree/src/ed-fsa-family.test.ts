  test("the calibration map nests provider, category, geography and band", () => {
    const root = createExplorerState();
    const programs = tree(root);
    expect(programs.groups.find((group) => group.id === PROVIDER.id)?.label).toBe(PROVIDER.label);
    expect(sorted(nodeLabels(programs, PROVIDER.id))).toEqual(
      sorted(CATEGORIES.map((category) => category.label)),
    );

    // A mixed category lists the United States first, then every state.
    const balance = selectExplorerNode(root, selection(programs, BALANCE.label));
    const geographies = tree(balance);
    expect(geographies.pathLabels).toEqual({ source: PROVIDER.label, program: BALANCE.label });
    const geographyLabels = nodeLabels(geographies, BALANCE.id);
    expect(geographyLabels[0]).toBe(UNITED_STATES.label);
    expect(sorted(geographyLabels)).toEqual(sorted([UNITED_STATES.label, ...STATES]));

    // Its United States targets split by age band and debt-size band.
    const nation = selectExplorerNode(balance, selection(geographies, UNITED_STATES.label));
    const bands = tree(nation);
    expect(bands.groups.map((group) => [group.id, group.label])).toEqual([
      [AGE.id, AGE.label],
      [DEBT_SIZE.id, DEBT_SIZE.label],
    ]);
    expect(sorted(nodeLabels(bands, AGE.id))).toEqual(sorted(AGE.values));
    expect(sorted(nodeLabels(bands, DEBT_SIZE.id))).toEqual(sorted(DEBT_SIZE.values));
    const smallest = selectExplorerNode(nation, selection(bands, "Less than 5K"));
    const smallestTargets = tree(smallest);
    expect(smallestTargets.pathLabels.dimensions).toEqual(["Less than 5K"]);
    expect(smallestTargets.groups.flatMap((group) => group.nodes.map((node) => node.label)))
      .toEqual(["Federal student loan balance, borrower debt size Less than 5K"]);

    // A state has one target, and its one location value adds no tier.
    const alabama = selectExplorerNode(balance, selection(geographies, "Alabama"));
    const alabamaTargets = tree(alabama);
    expect(alabamaTargets.pathLabels.dimensions).toEqual([]);
    expect(alabamaTargets.groups.map((group) => group.id)).toEqual(["targets"]);
    expect(alabamaTargets.groups[0].nodes.map((node) => node.label)).toEqual([
      "Federal student loan balance, Alabama",
    ]);

    // A one-target category is one United States node over its one target.
    for (const category of ONE_TARGET_CATEGORIES) {
      const program = selectExplorerNode(root, selection(programs, category.label));
      const places = tree(program);
      expect(nodeLabels(places, category.id)).toEqual([UNITED_STATES.label]);
      const only = tree(selectExplorerNode(program, selection(places, UNITED_STATES.label)));
      expect(only.groups.map((group) => group.id)).toEqual(["targets"]);
      expect(only.groups[0].nodes.map((node) => node.label)).toEqual([category.label]);
    }
  });

