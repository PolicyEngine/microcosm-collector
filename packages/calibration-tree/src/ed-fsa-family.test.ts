// The ED Federal Student Aid family that PolicyEngine/microcosm#1357 compiles,
// as schema 8 diagnostics rows: all 132 targets of its fit receipt, each with
// the hierarchy Microcosm derives from its Chronicle member facts. The fixture
// is generated by fixtures/ed-fsa-family/build_fixture.py, which names the
// source commit, each source file's sha256 and the Microcosm lines it follows.
//
// Its shape, per category:
// - federal_student_loan_balance and federal_student_loan_borrowers: 51 state
//   targets, each with its Borrower location as its one dimension, and 14
//   United States (country) targets: 5 Borrower age bands and 9 Borrower debt
//   size bands.
// - parent_plus_loan_balance: one United States target, Loan type = Parent PLUS.
// - loan_balance_excluding_parent_plus: one United States target with no
//   dimension; its five loan-type member facts share no groupby value.
