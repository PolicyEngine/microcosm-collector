function censusRows(): JsonObject[] {
  return CENSUS_STATES.map((state, index) => {
    const name = `census_population.resident_population.${state.id}`;
    return {
      name: `${name}@2024`,
      target_name: name,
      source: "Census population citation",
      target: 10_000_000 * (index + 1),
      initial_estimate: 9_000_000 * (index + 1),
      final_estimate: 10_050_000 * (index + 1),
      hierarchy: {
        provider: { id: "census_population", label: "Census population" },
        category: {
          id: "census_population.resident_population",
          label: "Resident population",
          provider_id: "census_population",
        },
        geography: { ...state, level: "state" },
        dimensions: [],
        target: { id: name, label: `Resident population, ${state.label}` },
      },
    };
  });
}

function schema8(): JsonObject {
  return { ...fixture, targets: [...censusRows(), ...structuredClone(fsaRows)] };
}

function calibrationOf(document: JsonObject, releaseId = RELEASE_ID) {
  return buildCalibration(document, releaseId, null, {}, {}, {}, "us");
}

const release = calibrationOf(schema8());

function targetsPage(query: Record<string, string>, facets: string[] = []) {
  const url = new URL("https://dashboard.test/api/microcosm/target-diagnostics");
  url.searchParams.set("limit", "500");
  for (const [key, value] of Object.entries(query)) url.searchParams.set(key, value);
  for (const facet of facets) url.searchParams.append("facet", facet);
  return latestMicrocosmTargetDiagnosticsPage(url.toString(), release);
}

const sorted = (values: readonly string[]) =>
  [...values].sort((left, right) => left.localeCompare(right));

function rowNamed(rows: Row[], targetName: string): Row {
  const row = rows.find((candidate) => candidate.target_name === targetName);
  if (!row) throw new Error(`No row is ${targetName}.`);
  return row;
}

function shown(row: Row) {
  return {
    source: row.source,
    source_label: row.source_label,
    variable: row.variable,
    variable_label: row.variable_label,
    variable_key: row.variable_key,
    family: row.family,
    geography: row.geography,
    geography_id: row.geography_id,
    level: row.level,
    breakdown: row.breakdown,
    target_dimensions: (row.target_dimensions as Row[]).map((dimension) => ({
      key: dimension.key,
      label: dimension.label,
      value: dimension.value,
      value_id: dimension.value_id,
    })),
    target_label: row.target_label,
    calibration_status: row.calibration_status,
  };
}

function nodeLabels(response: CalibrationTreeResponse, groupId: string): string[] {
  return response.groups.find((group) => group.id === groupId)?.nodes.map((node) => node.label) ??
    [];
}

function selection(response: CalibrationTreeResponse, label: string): ExplorerNodeSelection {
  const node = response.groups.flatMap((group) => group.nodes).find((candidate) =>
    candidate.label === label
  );
  if (!node) throw new Error(`No node is labelled ${label}.`);
  return node.selection;
}

